import assert from 'node:assert/strict';
import {chromium} from 'playwright-core';

const browser=await chromium.launch({channel:'msedge',headless:true,args:['--disable-gpu']});
try{
 const page=await browser.newPage({viewport:{width:1440,height:900}}),errors=[];
 page.on('pageerror',error=>errors.push(String(error)));
 await page.goto(process.env.AW_URL??'http://127.0.0.1:5176/');
 await page.waitForFunction(()=>!!window.__aw);
 const pdfId=await page.evaluate(()=>window.__aw.kernel.open({appId:'study',title:'AutoUE.pdf',rect:{x:150,y:80,w:650,h:680},props:{resource:'pdf',taskId:'comparison'}}));
 await page.waitForFunction(id=>document.querySelector(`[data-win="${id}"] .study-pdf-page[data-page="1"] canvas`)?.style.visibility==='visible',pdfId);
 await page.locator(`[data-win="${pdfId}"] .study-pdf-scroll`).evaluate(element=>{element.scrollTop=410});
 await page.locator('.study-mode-trigger').click();
 await page.locator('.system-drop.study-mode .study-mode-option').filter({hasText:'边界退让'}).click();
 const switchEnvironment=async(label)=>{await page.locator('.study-environment-trigger').click();await page.locator('.system-drop.study-environment .study-mode-option').filter({hasText:label}).click();};
 await switchEnvironment('文件管理');
 assert.equal(await page.locator(`[data-win="${pdfId}"]`).count(),0);
 assert.equal(await page.locator('[data-win]').count(),2);
 await page.locator('.study-mode-trigger').click();
 await page.locator('.system-drop.study-mode .study-mode-option').filter({hasText:'重要区域透出'}).click();
 await page.locator('.study-task-toggle').click();
 await page.getByRole('button',{name:'开始任务'}).click();
 await page.locator('.finder-row').filter({hasText:'download_8734.pdf'}).dblclick();
 await page.waitForFunction(()=>!!document.querySelector('[data-win] .file-study-document .study-pdf-reader'));
 await page.waitForFunction(()=>document.querySelector('.file-study-document .study-pdf-page canvas')?.style.visibility==='visible');
 await page.locator('.file-study-submit button').click();
 assert.equal(await page.getByText('已提交。本轮答案已记录。').count(),1);
 await page.getByRole('button',{name:'任务二'}).click();
 await page.getByRole('button',{name:'开始任务'}).click();
 await page.locator('.finder-row').filter({hasText:'download_6382.png'}).dblclick();
 await page.locator('.file-study-document img').waitFor();
 assert.ok(await page.locator('.file-study-document img').evaluate(image=>image.naturalWidth>0));
 await page.getByRole('button',{name:'放大'}).click();
 await page.locator('.file-study-submit button').click();
 await page.locator('.study-mode-trigger').click();
 await page.locator('.system-drop.study-mode .study-mode-option').filter({hasText:'截图停靠'}).click();
 await page.getByRole('button',{name:'任务三'}).click();
 await page.getByRole('button',{name:'开始任务'}).click();
 await page.locator('.finder-row').filter({hasText:'scan_5721.png'}).dblclick();
 await page.locator('.file-study-document img').waitFor();
 assert.ok(await page.locator('.file-study-document img').evaluate(image=>image.naturalWidth>0));
 await page.keyboard.press('Shift+s');
 const image=await page.locator('.file-study-document img').boundingBox();
 await page.mouse.move(image.x+40,image.y+40);await page.mouse.down();await page.mouse.move(image.x+180,image.y+160,{steps:8});await page.mouse.up();
 await page.waitForFunction(()=>window.__aw.kernel.list().some(win=>win.appId==='file-study-capture'));
 await page.waitForFunction(()=>window.__aw.kernel.list().some(win=>win.appId==='file-study-capture'&&!!win.group));
 await page.waitForFunction(()=>!window.__aw.kernel.list().some(win=>win.props.surfaceAnimating));
 await page.locator('.file-study-submit button').click();
 await page.waitForFunction(()=>document.querySelector('.study-task-details')?.textContent?.includes('已提交'));
 const results=await page.evaluate(()=>JSON.parse(localStorage.getItem('aquawindow.file-studies.results.v1')));
 assert.deepEqual(results.map(item=>item.task),['task1','task2','task3']);
 assert.ok(results.every(item=>item.correct));
 const fileWindows=await page.evaluate(()=>window.__aw.kernel.getState().order);
 await page.locator('.study-mode-trigger').click();
 await page.locator('.system-drop.study-mode .study-mode-option').filter({hasText:'融合与拆分'}).click();
 assert.deepEqual(await page.evaluate(()=>window.__aw.kernel.getState().order),fileWindows);
 await switchEnvironment('论文阅读');
 assert.equal(await page.evaluate(()=>window.__aw.ui.get().studyMode),'yield');
 assert.ok(await page.evaluate(id=>!!window.__aw.kernel.get(id),pdfId));
 assert.ok(await page.locator(`[data-win="${pdfId}"] .study-pdf-scroll`).evaluate(element=>element.scrollTop)>350);
 await switchEnvironment('文件管理');
 assert.equal(await page.evaluate(()=>window.__aw.ui.get().studyMode),'fusion');
 assert.deepEqual(await page.evaluate(()=>window.__aw.kernel.getState().order),fileWindows);
 assert.deepEqual(errors,[]);
 console.log('PASS: three file studies, submissions, separate desktop states and PDF reading position.');
}finally{await browser.close()}
