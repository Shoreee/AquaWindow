import assert from 'node:assert/strict';
import {chromium} from 'playwright-core';

const browser=await chromium.launch({channel:'msedge',headless:true,args:['--disable-gpu']});
try{
  const page=await browser.newPage({viewport:{width:1440,height:900}}),errors=[],agentCalls=[];
  page.on('pageerror',error=>errors.push(String(error)));
  page.on('request',request=>{if(request.url().includes('/api/agent/'))agentCalls.push(request.url());});
  await page.goto(process.env.AW_URL??'http://127.0.0.1:5174/');
  await page.waitForFunction(()=>!!window.__aw);
  const tech=await page.evaluate(()=>window.__aw.ui.get().tech);
  assert.equal(tech.peel,false);assert.equal(tech.depth,false);
  assert.equal(tech.yield,'deform');assert.equal(tech.cutout,true);assert.equal(tech.fusion,true);
  assert.equal(await page.evaluate(()=>window.__aw.ui.get().agentEnabled),false);
  const ids=await page.evaluate(()=>{
    const kernel=window.__aw.kernel;
    const a=kernel.open({appId:'study',title:'方法论',rect:{x:170,y:140,w:440,h:500},props:{resource:'methodology',taskId:'comparison'}});
    const b=kernel.open({appId:'study',title:'架构图',rect:{x:650,y:140,w:440,h:500},props:{resource:'architecture',taskId:'comparison'}});
    return {a,b};
  });
  const a=page.locator(`[data-win="${ids.a}"]`),b=page.locator(`[data-win="${ids.b}"]`);
  const dragTitle=await a.locator('.aw-title').boundingBox();
  await page.mouse.move(dragTitle.x+180,dragTitle.y+20);await page.mouse.down();
  await page.mouse.move(dragTitle.x+145,dragTitle.y+20,{steps:5});
  await page.waitForFunction(()=>document.documentElement.classList.contains('agent-cursor-enabled'));
  await page.mouse.up();
  await page.waitForFunction(id=>!window.__aw.kernel.get(id)?.props.agentMotion,ids.a);
  await page.evaluate(id=>window.__aw.kernel.setRect(id,{x:170,y:140,w:440,h:500}),ids.a);
  await a.locator('.aw-title').click({button:'right'});
  await page.getByRole('menuitem',{name:'框选重要区域'}).click();
  const content=await a.locator('.aw-content').boundingBox();
  await page.mouse.move(content.x+90,content.y+100);await page.mouse.down();
  await page.mouse.move(content.x+270,content.y+230,{steps:8});await page.mouse.up();
  assert.equal(await page.evaluate(id=>window.__aw.kernel.get(id).importance.length,ids.a),1);
  await page.evaluate(({a,b})=>{const k=window.__aw.kernel;k.setRect(b,{x:315,y:240,w:440,h:500});k.focus(b);},{a:ids.a,b:ids.b});
  await page.waitForFunction(()=>!!document.querySelector('.cut-rim'));
  await page.evaluate(({a,b})=>{const k=window.__aw.kernel;k.setRect(b,{x:620,y:140,w:440,h:500});k.focus(a);},{a:ids.a,b:ids.b});
  await a.locator('.aw-title').click({button:'right'});
  await page.getByRole('menuitem',{name:'与相邻窗口融合'}).click();
  await page.waitForFunction(({a,b})=>{const s=window.__aw.kernel.getState();return s.windows[a].group?.startsWith('surface:')&&s.windows[a].group===s.windows[b].group;},ids);
  await page.waitForFunction(()=>!Object.values(window.__aw.kernel.getState().windows).some(w=>w.props.surfaceAnimating));
  const title=await a.locator('.aw-title').boundingBox(),x=title.x+180,y=title.y+20;
  await page.mouse.move(x,y);await page.mouse.down();
  for(const delta of [65,-65,65,-65,65])await page.mouse.move(x+delta,y,{steps:5});
  await page.mouse.up();
  await page.waitForFunction(({a,b})=>{const s=window.__aw.kernel.getState();return !s.windows[a].group&&!s.windows[b].group;},ids);
  await a.locator('.aw-title').click({button:'right'});
  await page.getByRole('menuitem',{name:'收为胶囊…'}).click();
  assert.equal(await page.getByRole('dialog',{name:'胶囊布局预览'}).count(),1);
  assert.equal(await page.evaluate(id=>window.__aw.kernel.get(id).form,ids.a),'normal');
  await page.getByRole('button',{name:'确认收纳'}).click();
  await page.waitForFunction(id=>window.__aw.kernel.get(id).form==='capsule',ids.a);
  const pdfId=await page.evaluate(()=>window.__aw.kernel.open({appId:'study',title:'AutoUE.pdf',rect:{x:250,y:105,w:660,h:620},props:{resource:'pdf',taskId:'comparison'}}));
  const pdfWindow=page.locator(`[data-win="${pdfId}"]`),pageNumber=pdfWindow.getByRole('spinbutton',{name:'页码'});
  await page.waitForFunction(id=>{const input=document.querySelector(`[data-win="${id}"] input[aria-label="页码"]`);return input&&Number(input.max)>2;},pdfId);
  await pageNumber.fill('2');
  await pdfWindow.getByRole('button',{name:'放大'}).click();
  await page.waitForFunction(id=>{const win=document.querySelector(`[data-win="${id}"]`);return win?.querySelector('canvas')?.style.visibility==='visible'&&win.querySelector('.study-pdf-toolbar span:not(.study-pdf-spacer)')?.textContent==='120%';},pdfId);
  const pdfScroll=pdfWindow.locator('.study-pdf-scroll');
  await pdfScroll.evaluate(element=>{element.scrollTop=180;});
  await page.waitForFunction(id=>document.querySelector(`[data-win="${id}"] .study-pdf-scroll`)?.scrollTop>100,pdfId);
  const beforeScroll=await pdfScroll.evaluate(element=>element.scrollTop);
  await pdfWindow.locator('.aw-title').click({button:'right'});
  await page.getByRole('menuitem',{name:'收为胶囊…'}).click();
  await page.getByRole('button',{name:'确认收纳'}).click();
  await page.waitForFunction(id=>window.__aw.kernel.get(id).form==='capsule',pdfId);
  await pdfWindow.getByRole('button',{name:'释放胶囊中的全部窗口'}).click();
  await page.waitForFunction(id=>window.__aw.kernel.get(id).form==='normal',pdfId);
  await page.waitForFunction(id=>!window.__aw.kernel.get(id)?.props.agentRelease&&!window.__aw.kernel.get(id)?.props.agentMotion,pdfId);
  await page.waitForFunction(id=>document.querySelector(`[data-win="${id}"] canvas`)?.style.visibility==='visible',pdfId);
  assert.equal(await pageNumber.inputValue(),'2');
  assert.equal(await pdfWindow.locator('.study-pdf-toolbar span:not(.study-pdf-spacer)').textContent(),'120%');
  assert.ok(Math.abs((await pdfScroll.evaluate(element=>element.scrollTop))-beforeScroll)<8,'PDF scroll position survives capsule restoration');
  const browserId=await page.evaluate(()=>window.__aw.kernel.open({appId:'study',title:'浏览器',rect:{x:330,y:130,w:660,h:620},props:{resource:'browser',taskId:'external'}}));
  const browserWindow=page.locator(`[data-win="${browserId}"]`);
  await browserWindow.getByRole('textbox',{name:'搜索网页'}).fill('Pluto156 AutoUE');
  await browserWindow.getByRole('button',{name:'搜索'}).click();
  await browserWindow.getByRole('button',{name:/Pluto156\/AutoUE · GitHub/}).click();
  await browserWindow.locator('iframe').waitFor();
  await browserWindow.locator('.aw-title').click({button:'right'});
  await page.getByRole('menuitem',{name:'收为胶囊…'}).click();
  await page.getByRole('button',{name:'确认收纳'}).click();
  await page.waitForFunction(id=>window.__aw.kernel.get(id).form==='capsule',browserId);
  await browserWindow.getByRole('button',{name:'释放胶囊中的全部窗口'}).click();
  const qaId=await page.evaluate(()=>window.__aw.kernel.open({appId:'study',title:'AI 问答',rect:{x:390,y:160,w:660,h:560},props:{resource:'qa',taskId:'comparison'}}));
  await page.waitForFunction(id=>window.__aw.kernel.get(id).form==='normal',browserId);
  await page.waitForFunction(id=>!window.__aw.kernel.get(id)?.props.agentRelease&&!window.__aw.kernel.get(id)?.props.agentMotion,browserId);
  assert.ok(await page.evaluate(id=>!!window.__aw.kernel.get(id),qaId),'A window opened during capsule release stays open');
  await browserWindow.locator('iframe').waitFor();
  assert.match(await browserWindow.locator('.study-browser-page-label').textContent(),/github.com\/Pluto156\/AutoUE/);
  const qaWindow=page.locator(`[data-win="${qaId}"]`);
  await qaWindow.getByRole('textbox',{name:'输入问题'}).fill('窗口状态测试');
  await qaWindow.getByRole('button',{name:'发送'}).click();
  await qaWindow.locator('.aw-title').click({button:'right'});
  await page.getByRole('menuitem',{name:'收为胶囊…'}).click();
  await page.getByRole('button',{name:'确认收纳'}).click();
  await page.waitForFunction(id=>window.__aw.kernel.get(id).form==='capsule',qaId);
  await qaWindow.getByRole('button',{name:'释放胶囊中的全部窗口'}).click();
  await page.waitForFunction(id=>window.__aw.kernel.get(id).form==='normal',qaId);
  await qaWindow.getByText('窗口状态测试').waitFor();
  assert.deepEqual(errors,[]);assert.deepEqual(agentCalls,[]);
  console.log('PASS: study techniques, worm cursor, importance reveal, fusion, shake separation, capsule preview, PDF/browser/QA restoration and agent-off isolation.');
}finally{await browser.close();}
