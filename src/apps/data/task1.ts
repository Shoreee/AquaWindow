      "唐纳德・A・诺曼提出的情感化设计包含本能层、行为层、反思层三个层级。本能层对应视觉、触觉等即时感官感受；行为层聚焦操作效率、状态反馈、自然映射与可供性表达；反思层则和用户记忆、自我认同、长期情感体验相关。认知负荷理论指出，优秀的设计应当尽可能减少对用户工作记忆的占用，降低心智负担。",
